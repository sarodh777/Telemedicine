/**
 * Text-to-Speech audio narration helper.
 * Free, instantaneous, browser-native Web Speech API.
 */
let synth = typeof window !== "undefined" ? window.speechSynthesis : null;
let currentUtterance = null;

export const speakNarration = (text, lang = "en", onEnd = () => {}) => {
  if (!synth) return false;
  synth.cancel(); // Stop any ongoing speech

  if (!text) return false;

  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = lang === "hi" ? "hi-IN" : "en-US";
  utterance.rate = 0.95; // Slightly slower for clarity in rural healthcare
  utterance.pitch = 1.0;

  utterance.onend = () => {
    currentUtterance = null;
    onEnd();
  };
  utterance.onerror = () => {
    currentUtterance = null;
    onEnd();
  };

  currentUtterance = utterance;
  synth.speak(utterance);
  return true;
};

export const stopNarration = () => {
  if (synth) {
    synth.cancel();
    currentUtterance = null;
  }
};

